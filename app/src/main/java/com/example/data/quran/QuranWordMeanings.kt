    fun getMeaning(wordClean: String): String? {
        val clean = wordClean.replace(Regex("[\\p{Punct}«»۝\\d\\s]"), "").trim()
        if (dictionary.containsKey(clean)) return dictionary[clean]

        // Try partial match without prefixes
        val prefixes = listOf("و", "ف", "ب", "ل", "ك", "ال", "ٱل")
        for (p in prefixes) {
            if (clean.startsWith(p) && clean.length > p.length + 2) {
                val sub = clean.substring(p.length)
                if (dictionary.containsKey(sub)) return dictionary[sub]
            }
        }
        return null
    }

    fun extractWordMeaningsForAyah(ayahText: String): List<WordMeaning> {
        val words = ayahText.split(" ")
        val list = mutableListOf<WordMeaning>()
        val seen = mutableSetOf<String>()

        for (w in words) {
            val clean = w.replace(Regex("[\\p{Punct}«»۝\\d]"), "").trim()
            if (clean.length > 2 && !seen.contains(clean)) {
                val meaning = getMeaning(clean)
                if (meaning != null) {
                    list.add(WordMeaning(clean, meaning))
                    seen.add(clean)
                }
            }
        }
        return list
    }
